//OPERADORES DE COMPARAÇÃO
let idade = 18;

console.log(idade == '18');
console.log(idade === "18");
console.log(idade > 10);
console.log(idade < 8);
console.log(idade >= 35);
console.log(idade <= 20);   

//operadores de diferença
//!= verificar se é diferente (valor)
let a = 5;
let b = "5"

console.log(a != b);

console.log(a !== b);